CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('admin','staff','superadmin') NOT NULL DEFAULT 'staff',
 active BOOLEAN NOT NULL DEFAULT TRUE, token_version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 id INT PRIMARY KEY, name VARCHAR(150) NOT NULL DEFAULT 'Mon centre de formation',
 phone VARCHAR(40) NOT NULL DEFAULT '', address VARCHAR(255) NOT NULL DEFAULT '',
 currency VARCHAR(3) NOT NULL DEFAULT 'MAD', due_day INT NOT NULL DEFAULT 10,
 welcome_message TEXT NULL, reminder_message TEXT NULL, receipt_message TEXT NULL,
 makeup_message TEXT NULL, color CHAR(7) NOT NULL DEFAULT '#176658',
 color_dark CHAR(7) NOT NULL DEFAULT '#123b3a', logo MEDIUMTEXT NULL
) ENGINE=InnoDB;
