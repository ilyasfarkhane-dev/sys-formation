CREATE TABLE IF NOT EXISTS school_levels (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS students (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, first_name VARCHAR(80) NOT NULL,
 last_name VARCHAR(80) NOT NULL, phone VARCHAR(30) NOT NULL DEFAULT '', email VARCHAR(190) NOT NULL DEFAULT '',
 level VARCHAR(100) NOT NULL DEFAULT '', level_id INT UNSIGNED NULL,
 due_day TINYINT UNSIGNED NULL,
 notes TEXT NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (level_id) REFERENCES school_levels(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS specialties (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS teachers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, first_name VARCHAR(80) NOT NULL,
 last_name VARCHAR(80) NOT NULL DEFAULT '', phone VARCHAR(30) NOT NULL DEFAULT '',
 email VARCHAR(190) NOT NULL DEFAULT '', specialty VARCHAR(100) NOT NULL DEFAULT '',
 specialty_id INT UNSIGNED NULL,
 notes TEXT NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (specialty_id) REFERENCES specialties(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS study_groups (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, subject VARCHAR(100) NOT NULL,
 teacher VARCHAR(120) NOT NULL DEFAULT '', teacher_id INT UNSIGNED NULL,
 level VARCHAR(100) NOT NULL DEFAULT '', level_id INT UNSIGNED NULL,
 schedule VARCHAR(255) NOT NULL DEFAULT '', room VARCHAR(80) NOT NULL DEFAULT '',
 monthly_fee DECIMAL(12,2) NOT NULL, capacity INT NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (teacher_id) REFERENCES teachers(id),
 FOREIGN KEY (level_id) REFERENCES school_levels(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS enrollments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id INT UNSIGNED NOT NULL, group_id INT UNSIGNED NOT NULL,
 start_date DATE NOT NULL, end_date DATE NULL, monthly_fee DECIMAL(12,2) NOT NULL,
 UNIQUE KEY student_group_start (student_id,group_id,start_date),
 FOREIGN KEY (student_id) REFERENCES students(id), FOREIGN KEY (group_id) REFERENCES study_groups(id),
 INDEX(group_id,end_date)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, group_id INT UNSIGNED NOT NULL, date DATE NOT NULL,
 start_time TIME NOT NULL, end_time TIME NOT NULL, topic VARCHAR(255) NOT NULL DEFAULT '',
 UNIQUE KEY unique_session (group_id,date,start_time), FOREIGN KEY (group_id) REFERENCES study_groups(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS session_makeups (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, group_id INT UNSIGNED NOT NULL,
 original_date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
 makeup_date DATE NOT NULL, makeup_start TIME NOT NULL, makeup_end TIME NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY one_occurrence (group_id, original_date, start_time),
 FOREIGN KEY (group_id) REFERENCES study_groups(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS attendance (
 session_id INT UNSIGNED NOT NULL, student_id INT UNSIGNED NOT NULL,
 status ENUM('present','absent','late','excused') NOT NULL, note VARCHAR(255) NOT NULL DEFAULT '',
 PRIMARY KEY(session_id,student_id), FOREIGN KEY(session_id) REFERENCES sessions(id), FOREIGN KEY(student_id) REFERENCES students(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS invoices (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, enrollment_id INT UNSIGNED NOT NULL,
 period CHAR(7) NOT NULL, due_date DATE NOT NULL, amount DECIMAL(12,2) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY enrollment_period (enrollment_id,period), FOREIGN KEY(enrollment_id) REFERENCES enrollments(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS billing_periods (
 group_id INT UNSIGNED NOT NULL, period CHAR(7) NOT NULL, due_date DATE NOT NULL,
 PRIMARY KEY(group_id,period), FOREIGN KEY(group_id) REFERENCES study_groups(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, invoice_id INT UNSIGNED NOT NULL,
 amount DECIMAL(12,2) NOT NULL, method ENUM('cash','transfer','card','cheque') NOT NULL,
 paid_on DATE NOT NULL, note VARCHAR(255) NOT NULL DEFAULT '', created_by INT UNSIGNED NOT NULL,
 request_key CHAR(36) NOT NULL UNIQUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(invoice_id) REFERENCES invoices(id), FOREIGN KEY(created_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 action VARCHAR(80) NOT NULL, details VARCHAR(500) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
